export const STORAGE_I18N_KEY = 'vera_native_language';

export function getSavedNativeLanguage(): SupportedNativeLanguage {
  try {
    const saved = localStorage.getItem(STORAGE_I18N_KEY);
    if (saved && saved in TRANSLATIONS) {
      return saved as SupportedNativeLanguage;
    }
  } catch {}
  return 'en';
}

export function setSavedNativeLanguage(lang: SupportedNativeLanguage) {
  try {
    localStorage.setItem(STORAGE_I18N_KEY, lang);
    window.dispatchEvent(new CustomEvent('vera_lang_changed', { detail: lang }));
  } catch {}
}

export function t(key: string, lang: SupportedNativeLanguage = 'en'): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS['en'];
  return dict[key] || TRANSLATIONS['en'][key] || key;
}
